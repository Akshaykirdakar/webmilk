// tools\rptjson\*.json (made by rptdump.ps1 from the Crystal .rpt files) ->
//   frontend\js\rptdefs.js                  sections, objects, fonts, formulas, running totals of each report
//   backend\MilkBilling.Api\reports\fastsql.json   the SQL of each report (columns as C0, C1 ...)
// Run: node tools\genrptdefs.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(__dirname, 'rptjson');
const arr = x => (x == null ? [] : [].concat(x));

function obj(o) {
  const r = { k: o.k, n: o.n, x: o.x, y: o.y };
  if (o.w != null) r.w = o.w;
  if (o.h != null) r.h = o.h;
  const map = { Suppress: 's', HorAlignment: 'al', DecimalPlaces: 'dp', TextColor: 'c', BackColor: 'bg', BorderColor: 'bc', LineColor: 'lc', Right: 'r', Bottom: 'bt', LineStyle: 'ls', LineThickness: 'lt',
    SuppressIfDuplicated: 'sd', DateOrder: 'dord', YearType: 'yt', MonthType: 'mt', DayType: 'dt', DateFirstSeparator: 'ds1', DateSecondSeparator: 'ds2', ThousandsSeparators: 'ts',
    SuppressIfZero: 'sz', FillColor: 'fc', CanGrow: 'g', ExtendToBottomOfSection: 'xb', UseSystemDefaults: 'sysd' };
  for (const [a, b] of Object.entries(map)) if (o[a] !== undefined && o[a] !== null && o[a] !== false && o[a] !== '') r[b] = o[a];
  if (o.LeftLineStyle || o.RightLineStyle || o.TopLineStyle || o.BottomLineStyle) r.b = [o.LeftLineStyle, o.RightLineStyle, o.TopLineStyle, o.BottomLineStyle];
  if (o.end) r.end = o.end;
  if (o.t != null) r.t = o.t;
  if (o.f != null) r.f = o.f;
  if (o.sub != null) r.sub = o.sub;
  if (o.font) { r.font = o.font; r.size = o.size; if (o.bold) r.bold = 1; if (o.ital) r.ital = 1; if (o.und) r.und = 1; }
  return r;
}
function def(j) {
  const secs = {};
  const list = arr(j.sections);
  list.forEach((s, i) => {
    secs[s.n] = { h: s.h, sup: s.sup ? 1 : 0, o: arr(s.o).map(obj) };
    secs[s.n].o.forEach(o => {
      if (o.k === 4 && !o.end && (o.bt ?? 0) > s.h) {
        const after = list.slice(i + 1).filter(x => !x.sup);
        const e = after.find(x => x.h >= o.bt) || after[after.length - 1];
        if (e) o.end = e.n;
      }
    });
  });
  return {
    orient: j.orient, m: j.margins,
    formulas: Object.fromEntries(arr(j.formulas).map(f => [String(f.n).toLowerCase(), String(f.t || '')])),
    running: arr(j.running).map(r => ({ n: r.n, of: r.of, op: r.op, ev: r.ev, evf: r.evf || '', evn: r.evn || '', rs: r.rs, rsg: r.rsg, rsn: r.rsn || '', rsf: r.rsf || '' })),
    areas: arr(j.areas).map(a => ({ k: a.k, c: a.c || '', s: arr(a.s) })),
    secs
  };
}
// SELECT "T"."C", ... -> aliases C0.., column names in order; the selections Crystal pushed for its saved parameters are removed
function sql(j) {
  let s = String(j.sql || '').replace(/\s+/g, ' ').trim();
  if (!s) return null;
  const from = s.search(/ FROM /);
  const cols = [];
  const list = s.slice(0, from).replace(/^SELECT /, '').split(/, /).map(c => {
    const m = /^"([^"]+)"\."([^"]+)"$/.exec(c.trim());
    if (!m) throw new Error('column ' + c);
    cols.push((m[1] + '.' + m[2]).toUpperCase());
    return `${c.trim()} C${cols.length - 1}`;
  }).join(', ');
  let rest = s.slice(from);
  rest = rest.replace(/ (AND )?[A-Z_"]+\."[A-Z_]+" [<>]?= TO_DATE \('[^']*', '[^']*'\)/g, ' ')
    .replace(/ AND "[A-Z_]+"\."NTIME" = [\d.]+/g, ' ')
    .replace(/ AND "MILK_BILL_HEADER"\."VYEAR_CODE" = '[^']*' AND "MILK_BILL_HEADER"\."NFORTNO" = [\d.]+/g, ' ')
    .replace(/ WHERE "MILK_BILL_HEADER"\."VYEAR_CODE" = '[^']*' AND "MILK_BILL_HEADER"\."NFORTNO" = [\d.]+/g, ' ')
    .replace(/ +/g, ' ');
  return { sql: 'SELECT ' + list + rest, cols };
}
const defs = {}, sqls = {};
for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.json'))) {
  const name = f.replace('.json', '');
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8').replace(/^﻿/, ''));
  const d = def(j);
  d.subs = {};
  const q = { main: sql(j), subs: {} };
  for (const [k, v] of Object.entries(j.subs || {})) { d.subs[k] = def(v); q.subs[k] = sql(v); }
  defs[name] = d; sqls[name] = q;
}
fs.writeFileSync(path.join(root, 'frontend/js/rptdefs.js'), '/* Generated by tools/genrptdefs.js from the Crystal reports - do not edit */\nwindow.RPT = ' + JSON.stringify(defs) + ';\n');
fs.writeFileSync(path.join(root, 'backend/MilkBilling.Api/reports/fastsql.json'), JSON.stringify(sqls, null, 1));
console.log(Object.keys(defs).length + ' reports', Math.round(fs.statSync(path.join(root, 'frontend/js/rptdefs.js')).size / 1024) + ' KB');
