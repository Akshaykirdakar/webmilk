// Generates frontend/js/vbforms.js: the layout of the VB6 forms (position, size, font, font size, colours,
// TabIndex, caption, visibility, ListView columns) so the web screens are drawn exactly like the original forms.
// Usage: node tools/genforms.js ["D:/dairy/milk billing"] [frontend/js/vbforms.js]
const fs = require('fs'), path = require('path');
const SRC = process.argv[2] || 'D:/dairy/milk billing';
const OUT = process.argv[3] || path.join(__dirname, '..', 'frontend', 'js', 'vbforms.js');

const FORMS = {
  logon: 'cab_Logon', setup: 'HT_setup', collection: 'frmstudent_subject_MASTER', fortnight: 'frmstudent_subject',
  supplier: 'frmCDO_MAIN_YOJANA_MASTER', deductionMaster: 'frmDEDUCTION_MASTER', item: 'FRMDIS_PRODUCT_MASTER',
  bank: 'FRMbank_MASTER', village: 'FRMvillage_MASTER', purchase: 'frm_item_DEDUCTION_purch', deduction: 'frm_milk_DEDUCTION',
  jama: 'frm_milk_DEDUCTION_jama', adj: 'frm_milk_DEDUCTION_adj', billProc: 'frm_milk_bill_proc', bonusProc: 'frm_milk_bonus_proc',
  anudanProc: 'frm_milk_bill_anudan', backup: 'frmbackup', daily: 'repo_milk_daily', bill: 'repo_milk_Bill', register: 'repo_milk_Bill_reg',
  summary: 'repo_milk_Bill_summary', ledger: 'repo_milk_ledger', rcCow: 'repo_rate_chart', rcAnudan: 'repo_rate_chart_anudan',
  rcAnudan9: 'repo_rate_chart_anudan9.0', rcBuffalo: 'repo_rate_chart_buffalo', masterList: 'repo_chk_llist',
  anudan: 'repo_milk_Bill_anudan', sms: 'repo_milk_sms'
};
const TW = 15; // twips per pixel at 96 dpi
const px = v => Math.round((+v || 0) / TW);
const unq = v => { v = v.trim(); return v.startsWith('"') ? v.slice(1, v.lastIndexOf('"')) : v.replace(/\s*'.*$/, ''); };

function parse(file) {
  const t = new TextDecoder('windows-1252').decode(fs.readFileSync(path.join(SRC, file + '.frm'))).replace(/\r/g, '');
  const root = { kids: [], p: {}, font: {}, cols: [] };
  const st = [root];
  const props = []; // BeginProperty stack: {kind, obj}
  for (const l of t.split('\n')) {
    if (/^Attribute VB_Name/.test(l)) break;
    let m = l.match(/^\s*BeginProperty\s+(\w+)(?:\((\d+)\))?/);
    if (m) {
      const ctl = st[st.length - 1];
      if (m[1] === 'Font' && !props.length) props.push({ kind: 'font', obj: ctl.font });
      else if (m[1] === 'ColumnHeader') { const col = {}; ctl.cols.push(col); props.push({ kind: 'col', obj: col }); }
      else props.push({ kind: 'skip' });
      continue;
    }
    if (/^\s*EndProperty/.test(l)) { props.pop(); continue; }
    if (props.length) {
      const top = props[props.length - 1];
      m = l.match(/^\s*([\w.]+)\s*=\s*(.*)$/);
      if (m && top.kind !== 'skip') top.obj[m[1]] = unq(m[2]);
      continue;
    }
    m = l.match(/^\s*Begin\s+(\S+)\s+(\S+)/);
    if (m) { const c = { type: m[1].replace(/^.*\./, ''), name: m[2], p: {}, font: {}, kids: [], cols: [] }; st[st.length - 1].kids.push(c); st.push(c); continue; }
    if (/^\s*End\s*$/.test(l)) { st.pop(); continue; }
    m = l.match(/^\s*(\w+)\s*=\s*(.*)$/);
    if (m && st.length > 1) { const c = st[st.length - 1]; if (c.p[m[1]] === undefined) c.p[m[1]] = unq(m[2]); }
  }
  return root.kids[0];
}

function conv(k) {
  const p = k.p;
  const r = { n: k.name + (p.Index !== undefined ? '(' + p.Index + ')' : ''), t: k.type, x: px(p.Left), y: px(p.Top), w: px(p.Width), h: px(p.Height) };
  if (k.type === 'Line') { r.x = px(p.X1); r.y = px(p.Y1); r.x2 = px(p.X2); r.y2 = px(p.Y2); }
  if (p.Caption !== undefined) r.cap = p.Caption.replace(/&(?!&)/g, '');
  if (p.Text !== undefined && k.type !== 'ListView') r.txt = p.Text;
  if (k.font.Name) r.f = k.font.Name;
  if (k.font.Size) r.s = +k.font.Size;
  if (+k.font.Weight >= 600) r.b = 1;
  if (p.TabIndex !== undefined) r.ti = +p.TabIndex;
  if (p.TabStop === '0') r.nts = 1;
  if (p.Visible === '0') r.hid = 1;
  if (p.Enabled === '0') r.dis = 1;
  if (p.Locked === '-1') r.lock = 1;
  for (const [a, b] of [['Alignment', 'al'], ['BackStyle', 'bk'], ['Style', 'st'], ['BorderStyle', 'bs'], ['MaxLength', 'ml'], ['Appearance', 'ap']])
    if (p[a] !== undefined) r[b] = +p[a];
  if (p.BackColor) r.bg = p.BackColor;
  if (p.ForeColor) r.fg = p.ForeColor;
  if (p.PasswordChar) r.pw = 1;
  if (p.Tag !== undefined && p.Tag !== '') r.tag = p.Tag;
  if (p.WindowState !== undefined) r.ws = +p.WindowState;
  if (k.cols.length) r.cols = k.cols.map(c => ({ t: c.Text || '', w: px(c['Object.Width']), al: +(c.Alignment || 0) }));
  if (k.kids.length) r.kids = k.kids.map(conv);
  return r;
}

const result = {};
for (const [key, file] of Object.entries(FORMS)) {
  const f = parse(file);
  result[key] = {
    caption: f.p.Caption || '', w: px(f.p.ClientWidth), h: px(f.p.ClientHeight), bg: f.p.BackColor,
    f: f.font.Name, s: f.font.Size ? +f.font.Size : undefined, c: f.kids.map(conv)
  };
}
fs.writeFileSync(OUT, '// Generated by tools/genforms.js from the VB6 .frm files - do not edit by hand.\nwindow.VBF = ' + JSON.stringify(result) + ';\n', 'utf8');
console.log('forms:', Object.keys(result).length, 'size', fs.statSync(OUT).size);
