// Writes a Ghostscript Fontmap that maps the font names used in Crystal Reports PDFs
// ("DVBW-TTSurekh", "DVBW-TTSurekh,Bold", "Arial,Bold" ...) to the TrueType files in C:\Windows\Fonts.
const fs=require('fs'),path=require('path');
const FD='C:/Windows/Fonts', out=process.argv[2]||path.join(__dirname,'..','backend','MilkBilling.Api','crystal','Fontmap');
function names(file){ try{ const b=fs.readFileSync(file); if(b.readUInt32BE(0)===0x74746366) return null; const n=b.readUInt16BE(4); let fam='',sub='',full='';
 for(let i=0;i<n;i++){const o=12+i*16; if(b.toString('latin1',o,o+4)!=='name') continue; const off=b.readUInt32BE(o+8); const c=b.readUInt16BE(off+2), so=off+b.readUInt16BE(off+4);
  for(let j=0;j<c;j++){const r=off+6+j*12, pid=b.readUInt16BE(r), lid=b.readUInt16BE(r+4), nid=b.readUInt16BE(r+6), l=b.readUInt16BE(r+8), of=b.readUInt16BE(r+10); if(pid!==3||(lid!==0x409&&lid!==0)) continue; let s=''; for(let k=0;k<l;k+=2) s+=String.fromCharCode(b.readUInt16BE(so+of+k)); if(nid===1&&!fam) fam=s; if(nid===2&&!sub) sub=s; if(nid===4&&!full) full=s;}}
 return {fam,sub,full}; } catch { return null; } }
const lines=[]; const seen=new Set();
for(const f of fs.readdirSync(FD).filter(f=>/\.ttf$/i.test(f))){
  const x=names(path.join(FD,f)); if(!x||!x.fam) continue;
  const st=x.sub.toLowerCase(); const style= st.includes('bold')&&st.includes('italic')?',BoldItalic': st.includes('bold')?',Bold': st.includes('italic')?',Italic':'';
  const ps=(x.fam+style).replace(/ /g,'');
  for(const key of [x.fam.replace(/ /g,'')+style, x.fam+style]){ if(seen.has(key)) continue; seen.add(key);
    lines.push(`/${key.replace(/[()\s]/g,'')} (${FD}/${f}) ;`); }
}
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,'% Generated by tools/genfontmap.js\n'+lines.join('\n')+'\n');
console.log(lines.length+' entries -> '+out);
