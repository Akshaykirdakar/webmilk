// Copies the TrueType files of every font used by the VB forms (and data) into frontend/fonts and writes css/fonts.css
const fs=require('fs'),path=require('path');
global.window={}; require(path.join(__dirname,'..','frontend','js','vbforms.js'));
const used=new Set(['DVBW-TTSurekh','DVB-TTYogesh']);
for(const f of Object.values(window.VBF)){ if(f.f) used.add(f.f); f.c.forEach(c=>c.f&&used.add(c.f)); }
const FD='C:/Windows/Fonts';
function name(file){ const b=fs.readFileSync(file); const n=b.readUInt16BE(4); let fam='',sub='';
 for(let i=0;i<n;i++){const o=12+i*16; if(b.toString('latin1',o,o+4)!=='name') continue; const off=b.readUInt32BE(o+8); const c=b.readUInt16BE(off+2), so=off+b.readUInt16BE(off+4);
  for(let j=0;j<c;j++){const r=off+6+j*12, pid=b.readUInt16BE(r), nid=b.readUInt16BE(r+6), l=b.readUInt16BE(r+8), of=b.readUInt16BE(r+10); if(pid!==3) continue; let s=''; for(let k=0;k<l;k+=2) s+=String.fromCharCode(b.readUInt16BE(so+of+k)); if(nid===1) fam=s; if(nid===2) sub=s;}}
 return {fam,sub}; }
const files=fs.readdirSync(FD).filter(f=>/\.ttf$/i.test(f)&&/^dv/i.test(f));
const css=[]; const sys=[];
for(const u of used){
  const cands=files.map(f=>({f,...name(path.join(FD,f))})).filter(x=>x.fam===u);
  if(!cands.length){ sys.push(u); continue; }
  for(const c of cands){ const bold=/bold/i.test(c.sub), it=/italic/i.test(c.sub); if(it) continue;
    fs.copyFileSync(path.join(FD,c.f), path.join(__dirname,'..','frontend','fonts',c.f.toUpperCase()));
    css.push(`@font-face { font-family: '${u}'; src: url('../fonts/${c.f.toUpperCase()}') format('truetype'); font-weight: ${bold?'bold':'normal'}; }`); }
}
for(const u of used){ if(css.some(l=>l.includes("'"+u+"'")&&l.includes('bold'))&&!css.some(l=>l.includes("'"+u+"'")&&l.includes('normal'))) css.push(css.find(l=>l.includes("'"+u+"'")).replace('bold','normal')); }
fs.writeFileSync(path.join(__dirname,'..','frontend','css','fonts.css'),'/* Generated by tools/genfonts.js - DVB-TT (C-DAC ISM) fonts used by the VB forms */\n'+css.join('\n')+'\n');
console.log('embedded:',css.length,'faces; system fonts:',sys.join(', '));
